#!/usr/bin/env bash
# build.sh — reproducible build helper for the managed-mode open-code-review
# binary consumed by ReviewRouter (plan 56, section 12).
#
# Takes a clean upstream tree at a pinned commit, applies the exact managed
# compatibility patch set from ./patches, builds with a pinned Go toolchain,
# and emits:
#   <out>/opencodereview          the binary
#   <out>/opencodereview.sha256   its sha256
#   <out>/MANIFEST                upstream commit, patch digest, toolchain,
#                                 and the outcome schema version
#
# Usage:
#   tools/ocr/build.sh [--source <git-repo-or-dir>] [--out <dir>]
#
#   --source  Where to obtain clean upstream. A local path to a git clone of
#             alibaba/open-code-review (read via `git archive`, never
#             modified), or a URL to clone. Default:
#             https://github.com/alibaba/open-code-review.git
#   --out     Output directory. Default: <this-dir>/out
#
# Environment:
#   OCR_UPSTREAM  Same as --source.
#
# The build never writes outside <out> and the temporary work directory.
set -euo pipefail

TOOLCHAIN=go1.26.9
UPSTREAM_COMMIT=8eb83340a487b1150af00701b94f01af97e4b4d6 # v1.13.1
UPSTREAM_NAME=alibaba/open-code-review
OUTCOME_SCHEMA_VERSION=reviewrouter.ocr-outcome/v1
RELEASE_VERSION=1.13.1-rr.3
BUILD_FLAGS="-trimpath -buildvcs=false -ldflags -X=main.Version=$RELEASE_VERSION"

script_dir=$(cd "$(dirname "$0")" && pwd)
patches_dir="$script_dir/patches"
source_repo=${OCR_UPSTREAM:-https://github.com/$UPSTREAM_NAME.git}
out_dir="$script_dir/out"

while [ $# -gt 0 ]; do
  case "$1" in
    --source) source_repo=${2:?--source needs a value}; shift 2 ;;
    --out) out_dir=${2:?--out needs a value}; shift 2 ;;
    -h|--help) sed -n '2,26p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "build.sh: unknown argument: $1" >&2; exit 2 ;;
  esac
done

die() { echo "build.sh: $*" >&2; exit 1; }

command -v git >/dev/null || die "git is required"
command -v go >/dev/null || die "go is required on PATH (GOTOOLCHAIN=$TOOLCHAIN resolves the rest)"
command -v tar >/dev/null || die "tar is required"

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$@" | awk '{print $1}'
  else shasum -a 256 "$@" | awk '{print $1}'; fi
}

# --- 1. clean upstream tree at the pinned commit ---------------------------
work=$(mktemp -d "${TMPDIR:-/tmp}/ocr-build.XXXXXX")
trap 'rm -rf "$work"' EXIT
src="$work/src"
mkdir -p "$src"

if [ -d "$source_repo" ]; then
  git -C "$source_repo" cat-file -e "$UPSTREAM_COMMIT^{commit}" 2>/dev/null \
    || die "$source_repo does not contain upstream commit $UPSTREAM_COMMIT"
  echo "==> clean upstream $UPSTREAM_COMMIT from $source_repo (read-only)"
  git -C "$source_repo" archive "$UPSTREAM_COMMIT" | tar -x -C "$src"
else
  echo "==> clean upstream $UPSTREAM_COMMIT from $source_repo"
  git clone --quiet "$source_repo" "$src"
  git -C "$src" checkout --quiet --detach "$UPSTREAM_COMMIT" \
    || die "commit $UPSTREAM_COMMIT not found in $source_repo"
fi

# --- 2. apply the exact patch set ------------------------------------------
[ -d "$patches_dir" ] || die "no patches directory at $patches_dir"
patch_list=$(ls "$patches_dir"/*.patch 2>/dev/null | sort)
[ -n "$patch_list" ] || die "no patches found in $patches_dir"

echo "==> applying patch set"
for p in $patch_list; do
  git -C "$src" apply --check "$p" || die "patch does not apply cleanly: $(basename "$p")"
  git -C "$src" apply "$p"
  echo "    applied $(basename "$p")"
done

# --- 3. build with the pinned toolchain ------------------------------------
mkdir -p "$out_dir"
binary="$out_dir/opencodereview"
echo "==> building with GOTOOLCHAIN=$TOOLCHAIN"
( cd "$src" && env GOTOOLCHAIN="$TOOLCHAIN" CGO_ENABLED=0 \
    go build $BUILD_FLAGS -o "$binary" ./cmd/opencodereview ) \
  || die "go build failed"

# --- 4. digests + manifest -------------------------------------------------
binary_sha=$(sha256 "$binary")
{ printf '%s\n' "$binary_sha  opencodereview" ; } > "$binary.sha256"

# Patch digest: sha256 over the sorted, per-patch sha256 listing, so the
# manifest pins the exact patch bytes applied to upstream.
patch_listing="$work/patch-listing"
: > "$patch_listing"
for p in $patch_list; do
  printf '%s  %s\n' "$(sha256 "$p")" "$(basename "$p")" >> "$patch_listing"
done
patch_digest=$(sha256 "$patch_listing")
go_version=$(cd "$src" && env GOTOOLCHAIN="$TOOLCHAIN" go version | awk '{print $3}')
patch_count=$(wc -l < "$patch_listing" | tr -d '[:space:]')

cat > "$out_dir/MANIFEST" <<EOF
# ReviewRouter managed open-code-review build manifest.
# Generated by tools/ocr/build.sh; verify with tools/ocr/build.sh --source <upstream>.
upstream=$UPSTREAM_NAME
upstream_commit=$UPSTREAM_COMMIT
patch_count=$patch_count
patch_digest_sha256=$patch_digest
toolchain=$TOOLCHAIN
go_version=$go_version
outcome_schema_version=$OUTCOME_SCHEMA_VERSION
release_version=$RELEASE_VERSION
build_flags=CGO_ENABLED=0 $BUILD_FLAGS
binary=opencodereview
binary_sha256=$binary_sha
EOF
while read -r sum name; do
  printf 'patch_sha256.%s=%s\n' "$name" "$sum" >> "$out_dir/MANIFEST"
done < "$patch_listing"

echo "==> done"
echo "    binary:   $binary"
echo "    sha256:   $binary_sha"
echo "    manifest: $out_dir/MANIFEST"
